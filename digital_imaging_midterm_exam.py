# ==========================================
# 共用：讀取影像
# ==========================================
def read_image(image_path):
    """讀取影像；讀取失敗時回傳 None。"""
    if image_path is None:
        return None
    return cv2.imread(str(image_path), cv2.IMREAD_COLOR)


# ==========================================
# 1. 影像載入與基礎解析 (Metadata)
# ==========================================
def get_image_info(image_path):
    if image_path is None:
        return "請先上傳影像", None

    img = read_image(image_path)
    if img is None:
        return "無法讀取影像，請確認格式 (PNG, JPG, BMP)", None

    height, width, channels = img.shape
    file_size = os.path.getsize(image_path) / 1024  # KB
    dtype = img.dtype

    info_text = (
        "### 📋 影像基本中繼資訊\n"
        f"- **解析度 (Resolution):** {width} × {height} 像素\n"
        f"- **色彩維度 (Channels):** {channels} 通道 (BGR)\n"
        f"- **資料型態 (Data Type):** {dtype}\n"
        f"- **檔案大小 (File Size):** {file_size:.2f} KB"
    )
    return info_text, img


