# 4. 人臉偵測模組 (MediaPipe Tasks API)
# ==========================================

def detect_faces(image_path, confidence_threshold):

    if image_path is None:
        return None, "請先上傳影像"

    img = read_image(image_path)

    if img is None:
        return None, "無法讀取影像，請確認檔案格式。"

    # BGR 轉 RGB
    img_rgb = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

    height, width, _ = img.shape

    # MediaPipe Tasks API
    BaseOptions = mp.tasks.BaseOptions
    FaceDetector = mp.tasks.vision.FaceDetector
    FaceDetectorOptions = mp.tasks.vision.FaceDetectorOptions
    RunningMode = mp.tasks.vision.RunningMode

    # 模型路徑
    model_path = "/content/blaze_face_short_range.tflite"

    # 設定人臉偵測參數
    options = FaceDetectorOptions(
        base_options=BaseOptions(
            model_asset_path=model_path
        ),
        running_mode=RunningMode.IMAGE,
        min_detection_confidence=float(confidence_threshold)
    )

    # 將 NumPy 影像轉成 MediaPipe Image
    mp_image = mp.Image(
        image_format=mp.ImageFormat.SRGB,
        data=img_rgb
    )

    # 執行人臉偵測
    with FaceDetector.create_from_options(options) as detector:

        results = detector.detect(mp_image)

    # 複製影像，準備繪製結果
    annotated_img = img_rgb.copy()

    detections = results.detections
    details = []

    for idx, detection in enumerate(detections):

        # 取得信心度
        score = float(detection.categories[0].score)

        # 取得人臉框座標
        box = detection.bounding_box

        xmin = max(0, min(width - 1, box.origin_x))
        ymin = max(0, min(height - 1, box.origin_y))

        xmax = max(0, min(width - 1,
                          box.origin_x + box.width))

        ymax = max(0, min(height - 1,
                          box.origin_y + box.height))

        if xmax <= xmin or ymax <= ymin:
            continue

        # 繪製人臉框
        cv2.rectangle(
            annotated_img,
            (xmin, ymin),
            (xmax, ymax),
            (0, 255, 0),
            2
        )

        # 顯示人臉編號及信心度
        label = f"Face {idx + 1}: {score:.2f}"

        cv2.putText(
            annotated_img,
            label,
            (xmin, max(ymin - 10, 15)),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 0, 0),
            2
        )

        # 儲存偵測資訊
        details.append(
            f"- **人臉 #{idx + 1}**：信心度 = `{score:.4f}`，"
            f"位置 = `(x:{xmin}, y:{ymin}, "
            f"w:{xmax - xmin}, h:{ymax - ymin})`"
        )

    # 統計人臉數量
    face_count = len(details)

    summary_text = (
        "### 👤 人臉偵測結果報告\n"
        f"- **偵測到總人臉數：** **{face_count}** 具\n"
        f"- **設定信心門檻：** {confidence_threshold}\n"
        + ("\n".join(details)
           if details else "- 未偵測到符合條件的人臉。")
    )

    return annotated_img, summary_text

