# 3. 自訂卷積核空間濾波與 PSNR 計算
# ==========================================
def apply_custom_filter(
    image_path, k1, k2, k3, k4, k5, k6, k7, k8, k9, normalize
):
    if image_path is None:
        return None, "請先上傳影像"

    img = read_image(image_path)
    if img is None:
        return None, "無法讀取影像，請確認檔案格式。"

    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)

    # 組合 3×3 卷積核
    kernel = np.array(
        [[k1, k2, k3], [k4, k5, k6], [k7, k8, k9]],
        dtype=np.float32,
    )

    normalization_note = "未啟用"
    if normalize:
        kernel_sum = float(np.sum(kernel))
        if not np.isclose(kernel_sum, 0.0):
            kernel = kernel / kernel_sum
            normalization_note = "已啟用 (Normalized)"
        else:
            normalization_note = "已勾選，但卷積核總和為 0，因此未執行正規化"

    # 先以 float32 計算，避免負值或大於 255 的值在濾波時提早截斷。
    filtered_float = cv2.filter2D(gray, cv2.CV_32F, kernel)

    # 轉回 8-bit 影像前，將像素值限制在 0～255。
    filtered_gray = np.clip(np.rint(filtered_float), 0, 255).astype(np.uint8)
    filtered_rgb = cv2.cvtColor(filtered_gray, cv2.COLOR_GRAY2RGB)

    # PSNR：以原始灰階影像與實際輸出的 8-bit 濾波影像計算。
    mse = float(
        np.mean(
            (gray.astype(np.float64) - filtered_gray.astype(np.float64)) ** 2
        )
    )

    if mse == 0:
        psnr_text = "∞ (兩張影像完全相同)"
    else:
        max_i = 255.0
        psnr_val = 10 * np.log10((max_i**2) / mse)
        psnr_text = f"{psnr_val:.2f} dB"

    kernel_text = np.array2string(kernel, precision=4, suppress_small=True)
    result_text = f"""### 📊 濾波與品質評估結果
- **使用的卷積核 (Kernel):**
```text
{kernel_text}
```
- **正規化狀態:** {normalization_note}
- **均方誤差 (MSE):** {mse:.4f}
- **峰值信噪比 (PSNR):** **{psnr_text}**

#### 💡 PSNR 計算原理
1. **均方誤差 (MSE)**：計算原圖 I 與濾波後影像 K 之間像素差平方的平均值：

   $$MSE = \\frac{{1}}{{M \\times N}} \\sum_{{i=0}}^{{M-1}} \\sum_{{j=0}}^{{N-1}} [I(i,j)-K(i,j)]^2$$

2. **峰值信噪比 (PSNR)**：

   $$PSNR = 10 \\log_{{10}}\\left(\\frac{{MAX_I^2}}{{MSE}}\\right)$$

   其中 $MAX_I = 255$，代表 8 位元灰階影像的最大像素值。MSE 越小，PSNR 通常越高。"""

    return filtered_rgb, result_text



