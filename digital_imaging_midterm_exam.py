# 2. 多色彩空間轉換與同步直方圖分析
# ==========================================
def color_space_and_histogram(image_path, mode):
    if image_path is None:
        return None, None

    img_bgr = read_image(image_path)
    if img_bgr is None:
        return None, None

    img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)
    fig, ax = plt.subplots(figsize=(6, 4))

    try:
        if mode == "Original (RGB)":
            display_img = img_rgb
            colors = ("r", "g", "b")
            for i, color in enumerate(colors):
                hist = cv2.calcHist([img_rgb], [i], None, [256], [0, 256])
                ax.plot(hist, color=color, label=f"{color.upper()} channel")
            ax.set_title("RGB Histogram")

        elif mode == "Red Channel (R)":
            display_img = np.zeros_like(img_rgb)
            display_img[:, :, 0] = img_rgb[:, :, 0]
            hist = cv2.calcHist([img_rgb], [0], None, [256], [0, 256])
            ax.plot(hist, color="r", label="R channel")
            ax.set_title("Red Channel Histogram")

        elif mode == "Green Channel (G)":
            display_img = np.zeros_like(img_rgb)
            display_img[:, :, 1] = img_rgb[:, :, 1]
            hist = cv2.calcHist([img_rgb], [1], None, [256], [0, 256])
            ax.plot(hist, color="g", label="G channel")
            ax.set_title("Green Channel Histogram")

        elif mode == "Blue Channel (B)":
            display_img = np.zeros_like(img_rgb)
            display_img[:, :, 2] = img_rgb[:, :, 2]
            hist = cv2.calcHist([img_rgb], [2], None, [256], [0, 256])
            ax.plot(hist, color="b", label="B channel")
            ax.set_title("Blue Channel Histogram")

        elif mode in (
            "YUV - Y (Luminance)",
            "YUV - U (Chrominance)",
            "YUV - V (Chrominance)",
        ):
            img_yuv = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2YUV)
            y, u, v = cv2.split(img_yuv)

            if mode == "YUV - Y (Luminance)":
                channel, color, title = y, "black", "Y (Luminance) Histogram"
            elif mode == "YUV - U (Chrominance)":
                channel, color, title = u, "blue", "U (Chrominance) Histogram"
            else:
                channel, color, title = v, "red", "V (Chrominance) Histogram"

            display_img = cv2.cvtColor(channel, cv2.COLOR_GRAY2RGB)
            hist = cv2.calcHist([channel], [0], None, [256], [0, 256])
            ax.plot(hist, color=color, label=title.split(" ")[0])
            ax.set_title(title)

        else:
            plt.close(fig)
            return None, None

        ax.set_xlim([0, 256])
        ax.set_xlabel("Pixel Intensity (0-255)")
        ax.set_ylabel("Pixel Count")
        ax.legend()
        ax.grid(True, linestyle="--", alpha=0.6)

        # 新版 Matplotlib 使用 buffer_rgba()，再取前三個 RGB 通道。
        fig.canvas.draw()
        hist_img = np.asarray(fig.canvas.buffer_rgba())[..., :3].copy()

    finally:
        plt.close(fig)

    return display_img, hist_img


